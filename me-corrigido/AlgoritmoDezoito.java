public class AlgoritimoDezoito {

    public static void main(String[] args) {

        int vetor[] = new int[201];

        for (int i = 0; i <= 200; i++) {
            vetor[i] = i;
        }
        for (int i = 0; i <= 200; i++) {
            System.out.println("\n" +vetor[i]);
        }
    }
}
